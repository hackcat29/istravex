#!/bin/sh
# Regenerates unions_gen.go from the pinned go-stellar-sdk's XDR package.
set -e
cd "$(dirname "$0")/../.."
X=$(go list -m -f '{{.Dir}}' github.com/stellar/go-stellar-sdk)/xdr
{
  echo '// Code generated by gen-unions.sh from go-stellar-sdk/xdr. DO NOT EDIT.'
  echo; echo 'package main'; echo
  echo 'import "github.com/stellar/go-stellar-sdk/xdr"'; echo
  echo '// unions holds the zero value of every XDR union type, so the scanner can'
  echo '// enumerate the full set of cells (union arms) a reader can meet.'
  echo 'var unions = []any{'
  grep -oE '^func \(u [A-Za-z0-9]+\) SwitchFieldName\(\) string' "$X/xdr_generated.go" | sed -E 's/^func \(u ([A-Za-z0-9]+)\).*/	xdr.\1{},/'
  echo '}'
} > cmd/shape-scan/unions_gen.go
gofmt -w cmd/shape-scan/unions_gen.go
