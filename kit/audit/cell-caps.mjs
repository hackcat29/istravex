/** The CAP that introduced a cell, "base" if it predates CAPs, with the rule's note. */
export function capOf(cell) {
  for (const [test, cap, note] of RULES) {
    const hit = test instanceof RegExp ? test.test(cell) : test.endsWith(':') ? cell.startsWith(test) : cell === test;
    if (hit) return { cap, note };
  }
  return { cap: 'base' };
}
